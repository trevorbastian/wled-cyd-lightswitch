# PlatformIO pre-build script: validates the optional config.json in the project
# root and embeds it in the firmware as the default settings.
#
# Generates $BUILD_DIR/generated/default_config.h containing
#   DEFAULT_CONFIG_JSON  - compact JSON string ("{}" if there is no config.json)
#   DEFAULT_CONFIG_HASH  - changes whenever the config changes, so the device
#                          knows to re-apply it over settings edited on-screen

import hashlib
import json
import os
import sys

Import("env")  # noqa: F821 (provided by PlatformIO)

sys.path.insert(0, os.path.join(env.subst("$PROJECT_DIR"), "scripts"))  # noqa: F821
from config_schema import ConfigError, validate  # noqa: E402


def fail(msg):
    print(f"\nconfig.json: {msg}\n")
    env.Exit(1)  # noqa: F821


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate():
    project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
    gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
    path = os.path.join(project_dir, "config.json")

    if os.path.exists(path):
        try:
            with open(path, encoding="utf-8") as f:
                cfg = json.load(f)
            validate(cfg)
        except json.JSONDecodeError as e:
            fail(f"invalid JSON: {e}")
        except ConfigError as e:
            fail(str(e))
        compact = json.dumps(cfg, separators=(",", ":"))
        digest = hashlib.sha1(compact.encode()).hexdigest()[:12]
        print(f"Embedding config.json as default settings ({digest})")
    else:
        compact, digest = "{}", "none"

    header = (
        "// Generated by scripts/embed_config.py from config.json - do not edit\n"
        "#pragma once\n"
        f"#define DEFAULT_CONFIG_JSON {c_string(compact)}\n"
        f"#define DEFAULT_CONFIG_HASH {c_string(digest)}\n"
    )

    os.makedirs(gen_dir, exist_ok=True)
    out = os.path.join(gen_dir, "default_config.h")
    # Only rewrite on change so unchanged configs don't trigger a rebuild
    if not os.path.exists(out) or open(out, encoding="utf-8").read() != header:
        with open(out, "w", encoding="utf-8") as f:
            f.write(header)

    env.Append(CPPPATH=[gen_dir])  # noqa: F821


generate()
