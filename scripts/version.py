# PlatformIO pre-build script: generates $BUILD_DIR/generated/build_info.h with
#   FIRMWARE_NAME     - custom_firmware_name from platformio.ini
#   FIRMWARE_VERSION  - $CYD_FIRMWARE_VERSION if set (release builds), otherwise
#                       `git describe`, e.g. v1.2.0 or v1.2.0-3-gabc1234-dirty
#
# The browser flasher compares both with its manifest.json to decide whether
# the device needs an install or an update.

import os
import subprocess

Import("env")  # noqa: F821 (provided by PlatformIO)


def git_version(project_dir):
    try:
        out = subprocess.run(["git", "describe", "--tags", "--always", "--dirty"],
                             cwd=project_dir, capture_output=True, text=True, check=True)
        return out.stdout.strip() or "dev"
    except (OSError, subprocess.CalledProcessError):
        return "dev"


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate():
    project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
    gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
    name = env.GetProjectOption("custom_firmware_name")  # noqa: F821
    version = os.environ.get("CYD_FIRMWARE_VERSION") or git_version(project_dir)

    header = (
        "// Generated by scripts/version.py - do not edit\n"
        "#pragma once\n"
        f"#define FIRMWARE_NAME {c_string(name)}\n"
        f"#define FIRMWARE_VERSION {c_string(version)}\n"
    )

    os.makedirs(gen_dir, exist_ok=True)
    out = os.path.join(gen_dir, "build_info.h")
    # Only rewrite on change so an unchanged version doesn't trigger a rebuild
    if not os.path.exists(out) or open(out, encoding="utf-8").read() != header:
        with open(out, "w", encoding="utf-8") as f:
            f.write(header)

    env.Append(CPPPATH=[gen_dir])  # noqa: F821


generate()
